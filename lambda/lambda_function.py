"""Capture Lambda for the photogrammetry pipeline.

Accepts the metadata JSON produced by the frontend, stores it in the
`image-metadata` RDS (MySQL) database, and returns a pre-signed S3 PUT URL the
browser can use to upload the image bytes straight to the `image-bucket`.

The frontend only submits metadata (see frontend/app.js -> collectMetadata),
so the S3 object key is generated here and used as the primary key of the row.

Two distinct timestamps are persisted:
  * imageDt  - when the photo was captured, supplied by the user.
  * createDt - when the record was created, generated server-side.
"""

import json
import logging
import os
import re
import uuid
from datetime import datetime, timezone

import boto3
import pymysql
from botocore.config import Config
from botocore.exceptions import ClientError

logger = logging.getLogger()
logger.setLevel(os.environ.get("LOG_LEVEL", "INFO"))

# --- Configuration ---------------------------------------------------------

BUCKET_NAME = os.environ.get("IMAGE_BUCKET", "image-bucket")
DB_NAME = os.environ.get("DB_NAME", "image-metadata")
DB_HOST = os.environ.get("DB_HOST")
DB_PORT = int(os.environ.get("DB_PORT", "3306"))
DB_USER = os.environ.get("DB_USER")
DB_PASSWORD = os.environ.get("DB_PASSWORD")
KEY_PREFIX = os.environ.get("KEY_PREFIX", "images")
PRESIGN_EXPIRES_IN = int(os.environ.get("PRESIGN_EXPIRES_IN", "900"))
REGION = os.environ.get("AWS_REGION") or os.environ.get("AWS_DEFAULT_REGION")

# Columns accepted from the frontend. The keys are the JSON names emitted by
# the form; the values are the matching database column names.
NUMERIC_FIELDS = {
    "latitude": "latitude",
    "longitude": "longitude",
    "altitude": "altitude",
    "horizontalAccuracy": "horizontalAccuracy",
    "heading": "heading",
    "pitch": "pitch",
    "roll": "roll",
}
TEXT_FIELDS = {
    "location": "location",
    "description": "description",
}
# The user supplied capture time. `createDt` is generated by this function.
DATETIME_FIELDS = {
    "imageDt": "imageDt",
}

CONTENT_TYPE_EXTENSIONS = {
    "image/jpeg": ".jpg",
    "image/jpg": ".jpg",
    "image/png": ".png",
    "image/webp": ".webp",
    "image/gif": ".gif",
    "image/tiff": ".tif",
    "image/heic": ".heic",
}


class ValidationError(Exception):
    """Raised when the incoming request payload is not usable."""


def _response(status, body):
    return {
        "statusCode": status,
        "headers": {
            "Content-Type": "application/json",
            "Access-Control-Allow-Origin": "*",
            "Access-Control-Allow-Headers": "Content-Type",
            "Access-Control-Allow-Methods": "OPTIONS,POST",
        },
        "body": json.dumps(body),
    }


def parse_event(event):
    """Pull the metadata dict out of an API Gateway (or direct) event."""
    if event is None:
        raise ValidationError("Missing request body")

    payload = event
    if isinstance(event, dict) and "body" in event:
        body = event["body"]
        if body is None:
            raise ValidationError("Missing request body")
        if isinstance(body, (bytes, bytearray)):
            body = body.decode("utf-8")
        if isinstance(body, str):
            try:
                payload = json.loads(body)
            except json.JSONDecodeError as exc:
                msg = f"Body is not valid JSON: {exc}"
                raise ValidationError(msg) from exc
        else:
            payload = body

    if not isinstance(payload, dict):
        raise ValidationError("Request payload must be a JSON object")

    return payload


def _clean_number(value, field):
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        raise ValidationError(f"Field '{field}' must be a number") from None


def _clean_text(value, max_length=None):
    if value is None:
        return None
    if not isinstance(value, str):
        value = str(value)
    value = value.strip()
    if value == "":
        return None
    if max_length is not None and len(value) > max_length:
        raise ValidationError(f"Field exceeds {max_length} characters")
    return value


def _clean_datetime(value, field):
    """Normalize a datetime-local string into a MySQL DATETIME literal."""
    if value is None or value == "":
        return None
    if not isinstance(value, str):
        raise ValidationError(f"Field '{field}' must be a string")
    value = value.strip()
    if value == "":
        return None

    normalized = value.replace("T", " ")
    formats = ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y-%m-%d")
    for fmt in formats:
        try:
            parsed = datetime.strptime(normalized, fmt)
            return parsed.strftime("%Y-%m-%d %H:%M:%S")
        except ValueError:
            continue
    raise ValidationError(f"Field '{field}' is not a valid date/time")


def _utcnow():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def build_record(payload):
    """Validate the payload and map it onto the `images` table columns."""
    location = _clean_text(payload.get("location"), max_length=255)
    if not location:
        raise ValidationError("Field 'location' is required")

    record = {
        "location": location,
        "latitude": None,
        "longitude": None,
        "altitude": None,
        "horizontalAccuracy": None,
        "imageDt": None,
        "description": _clean_text(payload.get("description")),
        "heading": None,
        "pitch": None,
        "roll": None,
    }

    for json_name, column in NUMERIC_FIELDS.items():
        record[column] = _clean_number(payload.get(json_name), json_name)

    for json_name, column in DATETIME_FIELDS.items():
        record[column] = _clean_datetime(payload.get(json_name), json_name)

    # createDt is a separate, server-generated datetime. Honor an explicit
    # value only if one is provided, otherwise stamp the current UTC time.
    provided = _clean_datetime(payload.get("createDt"), "createDt")
    record["createDt"] = provided or _utcnow()

    # Unknown keys are ignored so the endpoint tolerates frontend drift.
    for json_name, column in TEXT_FIELDS.items():
        if column not in record:
            record[column] = _clean_text(payload.get(json_name))

    return record


def _sanitize_extension(name):
    _, ext = os.path.splitext(name or "")
    ext = re.sub(r"[^A-Za-z0-9.]", "", ext).lower()
    return ext if len(ext) <= 6 else ""


def build_object_key(payload):
    """Choose a unique S3 key for the incoming image."""
    content_type = _clean_text(payload.get("contentType"))
    filename = _clean_text(payload.get("filename") or payload.get("fileName"))

    extension = ""
    if content_type:
        extension = CONTENT_TYPE_EXTENSIONS.get(content_type.lower(), "")
    if not extension and filename:
        extension = _sanitize_extension(filename)

    return f"{KEY_PREFIX}/{uuid.uuid4().hex}{extension}"


def build_s3_url(key):
    if REGION:
        return f"https://{BUCKET_NAME}.s3.{REGION}.amazonaws.com/{key}"
    return f"https://{BUCKET_NAME}.s3.amazonaws.com/{key}"


def _db_credentials():
    """Return the DB connection settings from the environment."""
    return {
        "host": DB_HOST,
        "port": DB_PORT,
        "user": DB_USER,
        "password": DB_PASSWORD,
        "database": DB_NAME,
    }


def insert_metadata(record):
    """Insert one row into the `images` table."""
    creds = _db_credentials()
    columns = [
        "s3url",
        "location",
        "latitude",
        "longitude",
        "altitude",
        "horizontalAccuracy",
        "imageDt",
        "description",
        "heading",
        "pitch",
        "roll",
        "createDt",
    ]
    placeholders = ", ".join(["%s"] * len(columns))
    sql = (
        f"INSERT INTO images ({', '.join(columns)}) "
        f"VALUES ({placeholders})"
    )
    values = [record[column] for column in columns]

    connection = pymysql.connect(
        host=creds["host"],
        port=creds["port"],
        user=creds["user"],
        password=creds["password"],
        database=creds["database"],
        connect_timeout=5,
        cursorclass=pymysql.cursors.DictCursor,
    )
    try:
        with connection.cursor() as cursor:
            cursor.execute(sql, values)
        connection.commit()
    finally:
        connection.close()


def create_presigned_put(key, content_type=None):
    """Return a pre-signed URL the client can PUT the image to."""
    client = boto3.client(
        "s3",
        region_name=REGION,
        config=Config(signature_version="s3v4"),
    )
    params = {"Bucket": BUCKET_NAME, "Key": key}
    if content_type:
        params["ContentType"] = content_type

    return client.generate_presigned_url(
        "put_object",
        Params=params,
        ExpiresIn=PRESIGN_EXPIRES_IN,
        HttpMethod="PUT",
    )


def lambda_handler(event, context):
    if isinstance(event, dict):
        ctx = event.get("requestContext", {}).get("http", {})
        method = event.get("httpMethod") or ctx.get("method")
        if method and method.upper() == "OPTIONS":
            return _response(200, {"message": "ok"})

    try:
        payload = parse_event(event)
        record = build_record(payload)
        key = build_object_key(payload)
        s3url = build_s3_url(key)
        record["s3url"] = s3url
    except ValidationError as exc:
        logger.warning("Rejected request: %s", exc)
        return _response(400, {"error": "Failed to parse request"})

    try:
        insert_metadata(record)
    except pymysql.MySQLError:
        logger.exception("Failed to insert image metadata")
        return _response(500, {"error": "Failed to store image metadata"})

    try:
        content_type = _clean_text(payload.get("contentType")) or None
        upload_url = create_presigned_put(key, content_type=content_type)
    except ClientError:
        logger.exception("Failed to create pre-signed URL")
        return _response(500, {"error": "Failed to create upload URL"})

    logger.info("Registered image metadata for key=%s", key)

    return _response(
        201,
        {
            "s3url": s3url,
            "key": key,
            "bucket": BUCKET_NAME,
            "uploadUrl": upload_url,
            "expiresIn": PRESIGN_EXPIRES_IN,
        },
    )
